//! `BRepFill_Evolved::Add` (`BRepFill_Evolved.cxx:1844-1957`): merges one
//! elementary `Vevo` into the accumulated cut volume through a
//! `BRepTools_Quilt`.
//!
//! The reference first binds, for every vertex common to the combined profile
//! and the new profile, the edges `Vevo` generated on that vertex onto the
//! edges the accumulated volume generated (`cxx:1869-1911`), then adds
//! `Vevo.Shape()` to the quilt and copies the shapes `Vevo` generated that the
//! accumulated volume does not have yet (`cxx:1913-1954`).

use crate::brep_sweep::Quilt;
use crate::shape::{Edge, Wire};
use crate::topo_tools::vertices_of;

use super::evolved::BRepFillEvolved;
use super::shape_map::ShapeMap;
use super::side::{compare, relative};

impl BRepFillEvolved {
    /// `Add(Vevo, Prof, Glue)` (`cxx:1844-1957`).
    ///
    /// `Vevo` is only read, so the port takes it by shared reference where the
    /// reference takes a mutable one.
    pub fn add_with_glue(&mut self, vevo: &BRepFillEvolved, prof: &Wire, glue: &mut Quilt) {
        // `cxx:1859-1862`.
        if vevo.shape().is_none() {
            return;
        }

        // `cxx:1869-1911`: glue the edges generated by a shared vertex.
        for vv in vertices_of(&prof.0) {
            let (_ori, commun) = match self.my_profile.as_ref() {
                Some(my_profile) => relative(my_profile, prof, &vv),
                None => continue,
            };
            if !commun {
                continue;
            }
            let spine_keys: Vec<crate::shape::TopoShape> =
                self.my_map.keys().cloned().collect();
            for sp in spine_keys {
                let Some(mine) = self.my_map.list(&sp, &vv.0) else {
                    continue;
                };
                let Some(theirs) = vevo.my_map.list(&sp, &vv.0) else {
                    continue;
                };
                for (me, ve) in mine.iter().zip(theirs.iter()) {
                    let og = compare(&Edge(me.clone()), &Edge(ve.clone()));
                    glue.bind_edge(
                        &ve.oriented(crate::abs::Orientation::Forward),
                        &me.oriented(og),
                    );
                }
            }
        }

        // `cxx:1912`.
        if let Some(shape) = vevo.shape() {
            glue.add(shape);
        }

        // `cxx:1919-1954`: bring the shapes `Vevo` generated into `myMap`.
        let spine_keys: Vec<crate::shape::TopoShape> = vevo.my_map.keys().cloned().collect();
        for current_spine in spine_keys {
            let Some(inner) = vevo.my_map.find(&current_spine) else {
                continue;
            };
            let prof_keys: Vec<crate::shape::TopoShape> = inner.keys().cloned().collect();
            for current_prof in prof_keys {
                if !self.my_map.is_bound(&current_spine) {
                    self.my_map
                        .bind(&current_spine, ShapeMap::<Vec<crate::shape::TopoShape>>::new());
                }
                if self.my_map.list(&current_spine, &current_prof).is_some() {
                    continue;
                }
                self.my_map.list_mut(&current_spine, &current_prof);
                let Some(gen_shapes) = vevo.my_map.list(&current_spine, &current_prof) else {
                    continue;
                };
                for itl in gen_shapes.clone() {
                    // `cxx:1943-1950`: during `Glue.Add` the shared shapes are
                    // recreated.
                    let value = if glue.is_copied(&itl) {
                        glue.copy(&itl)
                    } else {
                        itl
                    };
                    self.my_map
                        .list_mut(&current_spine, &current_prof)
                        .push(value);
                }
            }
        }
    }
}
