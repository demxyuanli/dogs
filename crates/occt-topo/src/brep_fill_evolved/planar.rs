/// `Shape.Reversed()` (`TopoDS_Shape.hxx:256`): the same shape with the
/// complemented orientation.
fn reversed(shape: &TopoShape) -> TopoShape {
    shape.oriented(complement(shape.orientation()))
}

impl BRepFillEvolved {
    /// `PlanarPerform(Sp, Pr, Locus, Link, Join)` (`cxx:1267-1412`).
    ///
    /// `Join` is passed through to `BRepFill_OffsetWire::PerformWithBiLo`
    /// (`cxx:1311`); `myIsDone` is left to the caller, as in the reference
    /// (`PrivatePerform`, which sets it).
    pub fn planar_perform(
        &mut self,
        sp: &Face,
        pr: &Wire,
        locus: &BRepMat2dBisectingLocus,
        link: &mut BRepMat2dLinkTopoBilo,
        join: JoinType,
    ) {
        // `cxx:1275-1281`.
        self.my_spine = Some(Face(sp.0.oriented(Orientation::Forward)));
        self.my_profile = Some(pr.clone());
        self.my_map.clear();

        let builder = TopoBuilder::new();
        let mut shape = builder.make_compound_of(&[]).0;
        self.my_shape = Some(shape.clone());

        let my_spine = self.my_spine.clone().expect("spine was just set");
        let my_profile = self.my_profile.clone().expect("profile was just set");

        // `cxx:1285-1288`: `MapVP` and the reused offset tool.
        let mut map_vp: HashMap<ShapeMapKey, Option<TopoShape>> = HashMap::new();
        let mut paral = BRepFillOffsetWire::new();

        let mut prof_exp = WireExplorer::new();
        prof_exp.init(&my_profile, None);
        while prof_exp.more() {
            let Some(e) = prof_exp.current().cloned() else {
                prof_exp.next();
                continue;
            };

            // `cxx:1292-1294`.
            let mut fr = BRepAlgoFaceRestrictor::new();
            let mut off_anc = BRepFillOffsetAncestors::new();

            // `cxx:1296-1302`.
            let (v0, v1) = edge_vertices_oriented(&e);
            let (Some(v0), Some(v1)) = (v0, v1) else {
                prof_exp.next();
                continue;
            };
            let alt = altitud(&v0);
            let offset = [distance_to_oz(&v0), distance_to_oz(&v1)];
            let is_min_v1 = offset[0] < offset[1];

            for i in 0..2 {
                let vi = if i == 0 { &v0 } else { &v1 };
                let key = shape_map_key(&vi.0);

                // `cxx:1306-1332`.
                if !map_vp.contains_key(&key) {
                    // `cxx:1311-1313`.
                    paral.perform_with_bilo(&my_spine, offset[i], locus, link, join, alt);
                    off_anc.perform(&mut paral);
                    let paral_shape = paral.shape().cloned();
                    map_vp.insert(key.clone(), paral_shape.clone());

                    // `cxx:1318-1330`: every edge of the parallel records the
                    // shape it was generated from and the shapes the offset
                    // produced for that source.
                    if let Some(paral_shape_ref) = paral_shape {
                        for wc in edges_of(&paral_shape_ref) {
                            let gs = off_anc.ancestor(&wc.0).clone();
                            let inner = self
                                .my_map
                                .entry_or_bind(&gs, ShapeMap::<Vec<TopoShape>>::new);
                            if !inner.is_bound(&vi.0) {
                                // `cxx:1327`: the call is the second argument
                                // of `Bind`, so it only happens when the inner
                                // key is free (it folds `myMapSpine` once).
                                let generated = paral.generated_shapes(&gs);
                                inner.bind(&vi.0, generated);
                            }
                        }
                    }
                }

                // `cxx:1331-1339`.
                let rest = map_vp.get(&key).cloned().flatten();
                let to_reverse = if is_min_v1 { i == 1 } else { i == 0 };

                // `cxx:1340-1372`.
                let Some(rest) = rest else {
                    continue;
                };
                if rest.shape_type() == ShapeType::Wire {
                    let w = if to_reverse { reversed(&rest) } else { rest };
                    fr.add(&w);
                } else {
                    for wcop in explorer_shapes(&rest, ShapeType::Wire) {
                        let w = if to_reverse { reversed(&wcop) } else { wcop };
                        fr.add(&w);
                    }
                }
            }

            // `cxx:1379-1388`: restrict the faces bounded by the two parallels
            // on the spine translated to the altitude of `E`.
            let mut trsf = GpTrsf::identity();
            trsf.set_translation_vec(&GpVec::new(0.0, 0.0, alt));
            let location = TopLocLocation::composed(&trsf, TopLocLocation::identity());
            let moved = my_spine.0.located(&location);
            fr.init(Some(Face(moved)), false, false);
            fr.perform();

            // `cxx:1389-1411`.
            while fr.more() {
                let Some(f) = fr.current() else {
                    fr.next();
                    continue;
                };
                builder.add(&mut shape, &f.0);
                for ce in edges_of(&f.0) {
                    if !off_anc.has_ancestor(&ce.0) {
                        continue;
                    }
                    let init_e = off_anc.ancestor(&ce.0).clone();
                    self.my_map.list_mut(&init_e, &e.0).push(f.0.clone());
                }
                fr.next();
            }

            prof_exp.next();
        }

        self.my_shape = Some(shape);
    }
}
