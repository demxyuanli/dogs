//! `BRepFill_Evolved::PlanarPerform` (`BRepFill_Evolved.cxx:1267-1412`):
//! the sweep of `myProfile` along the planar spine `Sp`, using the parallels
//! of the spine vertices as the boundaries of the generated faces.
//!
//! Every profile edge `E` contributes the parallells of its two vertices: for
//! each vertex the reference offsets the spine by `DistanceToOZ` of that vertex
//! (`BRepFill_OffsetWire::PerformWithBiLo`, `cxx:1311`), records the offset
//! shapes and their ancestors in `myMap` (`cxx:1315-1330`), and feeds both
//! parallels - the one of the "lower" vertex reversed - to a
//! `BRepAlgo_FaceRestrictor` on the spine translated to `Altitud(V[0])`
//! (`cxx:1340-1385`). The restricted faces are appended to `myShape` and their
//! edges are recorded as generated by `E` (`cxx:1389-1411`).
//!
//! The reference declares `BRepFill_OffsetWire Paral` outside the profile loop
//! (`cxx:1288`) and only re-inits it per vertex; the port keeps that reuse
//! because `PerformWithBiLo` clears `myMap` but keeps `mySpine` / `myMapSpine`
//! / `myCallGen` between calls (`BRepFill_OffsetWire.cxx:695-701`,
//! `:390-444`), and `GeneratedShapes` must not re-fold `myMapSpine` a second
//! time.

